import logging
import re
import uuid

from django.apps import apps
from django.conf import settings
from django.core.cache import cache
from django.utils import timezone
from unidecode import unidecode

from app import config, helpers
from app.models import MediaTypes
from app.providers import gemini, services

logger = logging.getLogger(__name__)

CACHE_TIMEOUT = 60 * 60 * 24  # 1 day
# Extra lock time for the provider searches after Gemini responds
LOCK_EXTRA_TIMEOUT = 60 * 2

GLOBAL_COUNT = 16
MEDIA_COUNT = 12
# Ask for extra titles since some can't be resolved or are already tracked
EXTRA_REQUESTED = 8

LIKED_LIMIT = 50
DISLIKED_LIMIT = 25
LIBRARY_LIMIT = 200
SYNOPSIS_LIMIT = 600

SECTION_NAME = "ai_recommendations"

MEDIA_TYPES = [
    MediaTypes.TV.value,
    MediaTypes.MOVIE.value,
    MediaTypes.ANIME.value,
    MediaTypes.MANGA.value,
    MediaTypes.GAME.value,
    MediaTypes.BOOK.value,
    MediaTypes.COMIC.value,
    MediaTypes.BOARDGAME.value,
]

TYPE_LABELS = {
    MediaTypes.TV.value: ("TV show", "TV shows"),
    MediaTypes.MOVIE.value: ("movie", "movies"),
    MediaTypes.ANIME.value: ("anime", "anime"),
    MediaTypes.MANGA.value: ("manga", "manga"),
    MediaTypes.GAME.value: ("video game", "video games"),
    MediaTypes.BOOK.value: ("book", "books"),
    MediaTypes.COMIC.value: ("comic", "comics"),
    MediaTypes.BOARDGAME.value: ("board game", "board games"),
}

SYSTEM_INSTRUCTION = """\
You are a recommendation engine for a personal media tracker.
You recommend real, existing titles only. Never invent titles.
Use the exact official title as it appears on {provider_name} so it can be found by search.
Never recommend anything from the "Already in library" list.
Do not recommend sequels or later seasons unless the user has rated the earlier entry highly.
Prefer variety: mix well-known and lesser-known titles, different years and subgenres.
Write each "reason" in one short sentence (max 20 words), referencing the user's taste.
The user's explicit wishes and exclusions override everything else.
Respond only with JSON matching the schema."""  # noqa: E501

GLOBAL_PROMPT = """\
Recommend {count} {type_plural} for this user.

The user's ratings use a 0-10 scale.

{taste}

Base recommendations mostly on what the user liked. Avoid anything similar to what they disliked.
Ratings from other media types are signals of overall taste (themes, tone, genres)."""  # noqa: E501

MEDIA_PROMPT = """\
The user is viewing this {type_singular}:
{media_details}

Recommend {count} {type_plural} similar to this one that this user is likely to enjoy.

The user's ratings use a 0-10 scale.

{taste}

Similarity to the viewed title matters most; use the user's taste to choose among similar titles."""  # noqa: E501

LIKED_BLOCK = "Titles the user liked (score >= {score}):\n{lines}"
DISLIKED_BLOCK = "Titles the user disliked (score <= {score}):\n{lines}"
LIBRARY_BLOCK = "Already in library (do not recommend):\n{lines}"
POSITIVE_BLOCK = "The user's own wishes (follow them):\n{text}"
NEGATIVE_BLOCK = (
    "The user explicitly does not want (never recommend anything matching this):"
    "\n{text}"
)
NO_RATINGS = "The user has no ratings yet; recommend widely acclaimed titles."


class RecommendationsInProgressError(Exception):
    """Raised when recommendations are being generated by another request."""


def get_enabled_media_types(user):
    """Return the AI media types enabled in the user's preferences."""
    enabled_types = user.get_enabled_media_types()
    return [media_type for media_type in MEDIA_TYPES if media_type in enabled_types]


def get_media_types(user):
    """Return the enabled media types the user has tracked anything of."""
    return [
        media_type
        for media_type in get_enabled_media_types(user)
        if has_media(user, media_type)
    ]


def is_media_type_available(user, media_type):
    """Return whether the user can get AI recommendations for a media type."""
    return media_type in get_enabled_media_types(user) and has_media(
        user,
        media_type,
    )


def has_media(user, media_type):
    """Return whether the user tracks anything of a media type."""
    model = apps.get_model(app_label="app", model_name=media_type)
    return model.objects.filter(user=user).exists()


def global_cache_key(user_id, media_type):
    """Return the cache key for a user's recommendations of a media type."""
    return f"ai_recs_{user_id}_{media_type}"


def media_cache_key(user_id, media_type, source, media_id):
    """Return the cache key for a user's recommendations for a single media."""
    return f"ai_recs_{user_id}_{media_type}_{source}_{media_id}"


def invalidate_user(user):
    """Delete all cached AI recommendations for the user."""
    cache.delete_pattern(f"ai_recs_{user.id}_*")


def invalidate_media_type(user, media_type):
    """Delete the user's cached AI recommendations of a media type."""
    cache.delete(global_cache_key(user.id, media_type))
    cache.delete_pattern(f"{global_cache_key(user.id, media_type)}_*")


def global_recommendations(user, media_type, *, force=False):
    """Return cached or newly generated recommendations for a media type."""

    def generate():
        prompt = GLOBAL_PROMPT.format(
            count=GLOBAL_COUNT + EXTRA_REQUESTED,
            type_plural=TYPE_LABELS[media_type][1],
            taste=build_taste(user, media_type),
        )
        recommendations = gemini.recommend(system_instruction(media_type), prompt)
        return resolve(recommendations, media_type)

    return get_or_generate(
        global_cache_key(user.id, media_type),
        generate,
        force=force,
    )


def media_recommendations(user, media_type, source, media_id, *, force=False):
    """Return cached or newly generated recommendations similar to a media."""

    def generate():
        metadata = services.get_media_metadata(media_type, media_id, source)
        type_singular, type_plural = TYPE_LABELS[media_type]
        prompt = MEDIA_PROMPT.format(
            type_singular=type_singular,
            media_details=build_media_details(
                user, metadata, media_type, source, media_id
            ),
            count=MEDIA_COUNT + EXTRA_REQUESTED,
            type_plural=type_plural,
            taste=build_taste(user, media_type),
        )
        recommendations = gemini.recommend(system_instruction(media_type), prompt)
        items = resolve(recommendations, media_type)
        return [
            item
            for item in items
            if not (str(item["media_id"]) == str(media_id) and item["source"] == source)
        ]

    return get_or_generate(
        media_cache_key(user.id, media_type, source, media_id),
        generate,
        force=force,
    )


def get_or_generate(key, generate, *, force=False):
    """Return the cached value for ``key`` or generate and cache a new one."""
    if not force:
        data = cache.get(key)
        if data is not None:
            return data

    # Kept outside the "ai_recs_" prefix so invalidation doesn't release it
    lock_key = f"ai_lock_{key}"
    token = uuid.uuid4().hex
    if not cache.add(lock_key, token, lock_timeout()):
        data = None if force else cache.get(key)
        if data is not None:
            return data
        raise RecommendationsInProgressError

    try:
        data = {"generated_at": timezone.now(), "items": generate()}
        cache.set(key, data, CACHE_TIMEOUT)
    finally:
        # Don't release a lock that expired and was taken by another request
        if cache.get(lock_key) == token:
            cache.delete(lock_key)

    return data


def lock_timeout():
    """Return how long a generation can take when every Gemini model times out."""
    return len(settings.GEMINI_MODELS) * settings.GEMINI_TIMEOUT + LOCK_EXTRA_TIMEOUT


def enrich(request, items, limit):
    """Attach user data to items, drop tracked media and limit the results."""
    enriched_items = helpers.enrich_items_with_user_data(request, items, SECTION_NAME)
    return [item for item in enriched_items if item["media"] is None][:limit]


def system_instruction(media_type):
    """Return the system instruction for a media type."""
    provider_name = config.get_default_source_name(media_type).label
    return SYSTEM_INSTRUCTION.format(provider_name=provider_name)


def build_taste(user, media_type):
    """Return the prompt blocks describing the user's taste and library."""
    liked, disliked = get_rated_media(user)

    blocks = []
    if liked:
        blocks.append(
            LIKED_BLOCK.format(score=user.ai_liked_min_score, lines="\n".join(liked)),
        )
    if disliked:
        blocks.append(
            DISLIKED_BLOCK.format(
                score=user.ai_disliked_max_score,
                lines="\n".join(disliked),
            ),
        )
    if not blocks:
        blocks.append(NO_RATINGS)

    library = get_library_titles(user, media_type)
    if library:
        blocks.append(
            LIBRARY_BLOCK.format(lines="\n".join(f"- {title}" for title in library)),
        )

    positive = user.get_ai_prompt(media_type, "positive").strip()
    if positive:
        blocks.append(POSITIVE_BLOCK.format(text=positive))
    negative = user.get_ai_prompt(media_type, "negative").strip()
    if negative:
        blocks.append(NEGATIVE_BLOCK.format(text=negative))

    return "\n\n".join(blocks)


def get_rated_media(user):
    """Return prompt lines for the user's liked and disliked media."""
    if not user.ai_include_liked and not user.ai_include_disliked:
        return [], []

    latest_by_item = {}
    for media_type in get_enabled_media_types(user):
        model = apps.get_model(app_label="app", model_name=media_type)
        scored_media = (
            model.objects.filter(user=user, score__isnull=False)
            .select_related("item")
            .only("item__title", "item__media_type", "score", "created_at")
        )
        for media in scored_media:
            # Keep only the latest rating of repeated entries
            existing = latest_by_item.get(media.item_id)
            if existing is None or media.created_at > existing.created_at:
                latest_by_item[media.item_id] = media

    ranked_media = sorted(latest_by_item.values(), key=lambda media: -media.score)

    liked = []
    disliked = []
    for media in ranked_media:
        if user.ai_include_liked and media.score >= user.ai_liked_min_score:
            liked.append(media)
        elif user.ai_include_disliked and media.score <= user.ai_disliked_max_score:
            disliked.append(media)

    # Strongest dislikes first
    disliked.reverse()

    return (
        [format_rated_media(media) for media in liked[:LIKED_LIMIT]],
        [format_rated_media(media) for media in disliked[:DISLIKED_LIMIT]],
    )


def format_rated_media(media):
    """Return the prompt line for a rated media."""
    type_singular = TYPE_LABELS[media.item.media_type][0]
    return f"- {media.item.title} ({type_singular}) — {float(media.score):g}/10"


def get_library_titles(user, media_type):
    """Return the titles the user already tracks for a media type."""
    model = apps.get_model(app_label="app", model_name=media_type)
    titles = (
        model.objects.filter(user=user)
        .order_by("-created_at")
        .values_list("item__title", flat=True)
    )
    return list(dict.fromkeys(titles))[:LIBRARY_LIMIT]


def build_media_details(user, metadata, media_type, source, media_id):
    """Return the prompt lines describing the viewed media."""
    lines = [f"Title: {metadata['title']}"]

    genres = metadata.get("genres")
    if genres:
        lines.append(f"Genres: {', '.join(genres)}")

    synopsis = metadata.get("synopsis")
    if synopsis:
        lines.append(f"Synopsis: {synopsis[:SYNOPSIS_LIMIT]}")

    model = apps.get_model(app_label="app", model_name=media_type)
    user_media = (
        model.objects.filter(
            user=user,
            item__media_id=media_id,
            item__source=source,
            score__isnull=False,
        )
        .order_by("-created_at")
        .first()
    )
    if user_media is not None:
        lines.append(f"The user rated it {float(user_media.score):g}/10.")

    return "\n".join(lines)


def resolve(recommendations, media_type):
    """Match Gemini recommendations to search results of the default source."""
    source = config.get_default_source_name(media_type).value

    items = []
    seen_ids = set()
    for recommendation in recommendations:
        try:
            results = services.search(
                media_type,
                recommendation["title"],
                1,
                source,
            )["results"]
        except services.ProviderAPIError:
            logger.warning("Could not resolve AI recommendation %s", recommendation)
            continue

        match = best_match(results, recommendation)
        if match is None or str(match["media_id"]) in seen_ids:
            continue

        seen_ids.add(str(match["media_id"]))
        items.append({**match, "reason": recommendation["reason"]})

    return items


def best_match(results, recommendation):
    """Return the search result with the recommended title, if any."""
    title = normalize_title(recommendation["title"])
    year = recommendation.get("year")
    same_title = [
        result for result in results if normalize_title(result["title"]) == title
    ]
    for result in same_title:
        if year is None or result.get("release_year") in (None, year):
            return result
    # A different title would show Gemini's reason for the wrong media
    return same_title[0] if same_title else None


def normalize_title(title):
    """Return a lowercase ASCII title with only letters and digits."""
    return re.sub(r"[^a-z0-9]", "", unidecode(title).lower())
