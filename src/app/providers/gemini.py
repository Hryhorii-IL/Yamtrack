import logging

import httpx
import requests
from django.conf import settings
from django.core.cache import cache
from google import genai
from google.genai import errors, types
from pydantic import BaseModel

from app.providers import services

logger = logging.getLogger(__name__)

PROVIDER = "gemini"
AUTH_ERROR_CODES = (401, 403)
# How long to try other models first after a model fails
UNAVAILABLE_TIMEOUT = 60 * 10


class Recommendation(BaseModel):
    """A single title recommended by Gemini."""

    title: str
    year: int | None = None
    reason: str


class RecommendationList(BaseModel):
    """Structured response returned by Gemini."""

    items: list[Recommendation]


def recommend(system_instruction, prompt):
    """Return recommendation dicts from the first configured model that works."""
    if not settings.GEMINI_MODELS:
        raise_api_error(None, "No Gemini models configured")

    client = genai.Client(
        api_key=settings.GEMINI_API_KEY,
        http_options=types.HttpOptions(timeout=settings.GEMINI_TIMEOUT * 1000),
    )
    *fallback_models, last_model = get_models()
    for model in fallback_models:
        try:
            return generate_or_skip(client, model, system_instruction, prompt)
        except services.ProviderAPIError as error:
            # The API key is shared by all models, so retrying won't help
            if error.status_code in AUTH_ERROR_CODES:
                raise
            logger.warning("Gemini model %s failed, trying the next model", model)

    return generate_or_skip(client, last_model, system_instruction, prompt)


def get_models():
    """Return the configured models with recently failed ones moved last."""
    unavailable = cache.get_many(
        [unavailable_cache_key(model) for model in settings.GEMINI_MODELS],
    )
    return sorted(
        settings.GEMINI_MODELS,
        key=lambda model: unavailable_cache_key(model) in unavailable,
    )


def generate_or_skip(client, model, system_instruction, prompt):
    """Generate with a model and skip it for a while if it fails."""
    try:
        return generate(client, model, system_instruction, prompt)
    except services.ProviderAPIError as error:
        if error.status_code not in AUTH_ERROR_CODES:
            cache.set(unavailable_cache_key(model), 1, UNAVAILABLE_TIMEOUT)
        raise


def unavailable_cache_key(model):
    """Return the cache key marking a model as recently failed."""
    return f"gemini_unavailable_{model}"


def generate(client, model, system_instruction, prompt):
    """Return recommendation dicts generated by a single Gemini model."""
    try:
        response = client.models.generate_content(
            model=model,
            contents=prompt,
            config=types.GenerateContentConfig(
                system_instruction=system_instruction,
                response_mime_type="application/json",
                response_schema=RecommendationList,
            ),
        )
    except errors.APIError as error:
        raise_api_error(error.code, f"{model}: {error.message}")
    except httpx.HTTPError as error:
        raise_api_error(None, f"{model}: {error or type(error).__name__}")

    parsed = response.parsed
    if not isinstance(parsed, RecommendationList):
        raise_api_error(None, f"{model}: invalid response")

    return [recommendation.model_dump() for recommendation in parsed.items]


def raise_api_error(status_code, message):
    """Raise a ProviderAPIError with the Gemini status code and message."""
    mock_response = type(
        "obj",
        (object,),
        {"status_code": status_code, "text": message},
    )()
    mock_error = requests.exceptions.HTTPError(response=mock_response)
    raise services.ProviderAPIError(PROVIDER, mock_error, message)
